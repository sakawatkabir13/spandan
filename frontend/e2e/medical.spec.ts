import { test, expect } from '@playwright/test';
import { readCode, verifyEmail } from './mailbox';

test('patient onboarding, private medical upload, booked-doctor review and sharing revocation', async ({ page, browser }) => {
  const suffix = Date.now().toString();
  const password = 'MedicalWorkflowPassword123!';
  const doctorEmail = `records-doctor-${suffix}@example.com`;
  await page.request.post('/api/v1/auth/registration-code', { data: { email: doctorEmail } });
  const doctor = (await (await page.request.post('/api/v1/auth/register/doctor', { data: { email: doctorEmail, email_otp: await readCode(doctorEmail), password, full_name: 'Records Browser Doctor', phone_number: '015' + suffix.slice(-8), medical_registration_number: 'RECORDS-' + suffix } })).json()).data;
  const doctorHeaders = { Authorization: `Bearer ${doctor.access_token}` };
  const admin = (await (await page.request.post('/api/v1/auth/login', { data: { email: 'e2e-admin@example.com', password: 'E2EAdminPassword123!' } })).json()).data;
  await page.request.post(`/api/v1/doctors/${doctor.user.doctor_profile.id}/verify`, { headers: { Authorization: `Bearer ${admin.access_token}` }, data: { status: 'approved' } });
  const chamber = (await (await page.request.post('/api/v1/chambers', { headers: doctorHeaders, data: { name: 'Records Browser Chamber', address: 'Test Road', district: 'Dhaka', area: 'Test', consultation_fee: 500, follow_up_fee: 300 } })).json()).data;
  const schedule = (await (await page.request.post('/api/v1/schedules', { headers: doctorHeaders, data: { chamber_id: chamber.id, schedule_date: new Date(Date.now() + 86400000).toISOString().slice(0, 10), start_time: '17:00', end_time: '20:00', maximum_patients: 5 } })).json()).data;
  const email = `records-patient-${suffix}@example.com`;
  await page.setViewportSize({ width: 390, height: 844 });
  await page.goto('/register');
  await page.getByLabel('Full Name', { exact: true }).fill('Records Browser Patient');
  await page.getByLabel('Email Address', { exact: true }).fill(email);
  await page.getByLabel('Phone Number', { exact: true }).fill('014' + suffix.slice(-8));
  await page.getByLabel('Password', { exact: true }).fill(password);
  await verifyEmail(page, email);
  await page.getByRole('button', { name: 'Register as Patient', exact: true }).click();
  await expect(page).toHaveURL(/profile\?onboarding=1/);
  await page.getByLabel('Date of birth', { exact: true }).fill('1996-04-12');
  await page.getByLabel('Gender', { exact: true }).selectOption('Male');
  await page.getByLabel('Emergency contact', { exact: true }).fill('+8801700000044');
  await page.getByRole('button', { name: 'Save Profile', exact: true }).click();
  await expect(page.getByRole('status').filter({ hasText: 'Profile saved.' })).toBeVisible();
  await page.getByLabel('Allergies', { exact: true }).fill('Penicillin');
  await page.getByLabel('I have reviewed my medical history', { exact: false }).check();
  await page.getByRole('button', { name: 'Save medical history', exact: true }).click();
  await expect(page.getByText('Medical history and sharing preferences saved.', { exact: true })).toBeVisible();
  await expect(page.getByRole('progressbar')).toHaveAttribute('aria-valuenow', '100');
  await page.getByLabel('Report title', { exact: true }).fill('Blood test for visit');
  await page.getByLabel('Report file', { exact: true }).setInputFiles({ name: 'blood-count.pdf', mimeType: 'application/pdf', buffer: Buffer.from('%PDF-1.4\n1 0 obj\n<< /Type /Catalog >>\nendobj\n%%EOF\n') });
  await page.getByRole('button', { name: 'Upload report', exact: true }).click();
  await expect(page.getByRole('heading', { name: 'Blood test for visit', exact: true })).toBeVisible();
  await page.screenshot({ path: '/tmp/spandan-medical-profile.png', fullPage: true });
  const token = await page.evaluate(() => localStorage.getItem('spandan_access_token'));
  const appointment = (await (await page.request.post('/api/v1/appointments', { headers: { Authorization: `Bearer ${token}` }, data: { schedule_id: schedule.id } })).json()).data;
  const doctorContext = await browser.newContext();
  const doctorPage = await doctorContext.newPage();
  await doctorPage.goto('/login');
  await doctorPage.getByLabel('Email Address', { exact: true }).fill(doctorEmail);
  await doctorPage.getByLabel('Password', { exact: true }).fill(password);
  await doctorPage.getByRole('button', { name: 'Sign In', exact: true }).click();
  await expect(doctorPage).toHaveURL(/dashboard\/doctor/);
  await doctorPage.goto(`/dashboard/doctor/queue?schedule_id=${schedule.id}`);
  await doctorPage.getByRole('link', { name: 'Medical history & reports', exact: true }).click();
  await expect(doctorPage).toHaveURL(new RegExp(appointment.id));
  await expect(doctorPage.getByText('The patient has not enabled medical-record sharing.', { exact: false })).toBeVisible();
  await expect(doctorPage.getByText('Penicillin', { exact: true })).toHaveCount(0);
  await page.getByLabel('Share my medical history and reports', { exact: false }).check();
  await page.getByRole('button', { name: 'Save medical history', exact: true }).click();
  await expect(page.getByText('Medical history and sharing preferences saved.', { exact: true })).toBeVisible();
  await doctorPage.getByRole('button', { name: 'Refresh records', exact: true }).click();
  await expect(doctorPage.getByText('Penicillin', { exact: true })).toBeVisible();
  await doctorPage.screenshot({ path: '/tmp/spandan-doctor-records.png', fullPage: true });
  const download = doctorPage.waitForEvent('download');
  await doctorPage.getByRole('button', { name: /^Download report/ }).click();
  expect((await download).suggestedFilename()).toBe('blood-count.pdf');
  await page.getByLabel('Share my medical history and reports', { exact: false }).uncheck();
  await page.getByRole('button', { name: 'Save medical history', exact: true }).click();
  await expect(page.getByText('Medical history and sharing preferences saved.', { exact: true })).toBeVisible();
  await doctorPage.getByRole('button', { name: 'Refresh records', exact: true }).click();
  await expect(doctorPage.getByText('Penicillin', { exact: true })).toHaveCount(0);
  await expect(doctorPage.getByRole('button', { name: /^Download report/ })).toHaveCount(0);
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
  page.once('dialog', dialog => dialog.accept());
  await page.getByRole('button', { name: /^Remove/ }).click();
  await expect(page.getByRole('heading', { name: 'Blood test for visit', exact: true })).toHaveCount(0);
  await doctorContext.close();
});
